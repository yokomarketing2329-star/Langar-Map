const DICTS: Record<Lang, Dict> = { en, hi, pa }
export type TKey = keyof Dict

function detectLang(): Lang {
  try {
    const saved = localStorage.getItem('bm_lang') as Lang | null
    if (saved && saved in DICTS) return saved
  } catch { /* ignore */ }
  const nav = (navigator.languages?.[0] || navigator.language || 'en').toLowerCase()
  if (nav.startsWith('pa')) return 'pa'
  if (nav.startsWith('hi')) return 'hi'
  return 'en'
}

interface I18n {
  lang: Lang
  setLang: (l: Lang) => void
  t: (k: TKey, vars?: Record<string, string | number>) => string
  /** Translate an API error code like "rate_limited". */
  err: (code: string) => string
  locale: string
}

const Ctx = createContext<I18n | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang)
  useEffect(() => { document.documentElement.lang = lang }, [lang])
  const value = useMemo<I18n>(() => {
    const dict = DICTS[lang]
    const t = (k: TKey, vars?: Record<string, string | number>) => {
      let s: string = dict[k] ?? en[k] ?? k
      if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b))
      return s
    }
    return {
      lang,
      setLang: (l) => { setLangState(l); try { localStorage.setItem('bm_lang', l) } catch { /* ignore */ } },
      t,
      err: (code) => t((`err_${code}` in en ? `err_${code}` : 'err_generic') as TKey),
      locale: lang === 'en' ? 'en-IN' : lang === 'hi' ? 'hi-IN' : 'pa-IN',
    }
  }, [lang])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): I18n {
  const v = useContext(Ctx)
  if (!v) throw new Error('I18nProvider missing')
  return v
}
